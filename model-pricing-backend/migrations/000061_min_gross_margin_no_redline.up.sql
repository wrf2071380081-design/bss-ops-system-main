-- 毛利率不再设红线（对齐原型口径）。
--
-- 原型里毛利率只做「提示」不做「拦截」：低于 3% 弹一次「严重报价提示」，销售点「已知悉」就能继续，
-- 风险交给审批人把关。但服务端一直用 sys_config.min_gross_margin(0.15) 算 floor，
-- 毛利率一旦低于 15% 就直接 409 拒单——两边口径打架，前端再怎么做提示都会被后端挡回去。
--
-- 这里把红线降到 0：floor = 采购成本本身。
--   - 低于 3% 仍在前端弹提示（交互不变）；
--   - 「低于采购成本」这种真亏本的报价依旧会被服务端拒绝（floor 还在，只是从"有毛利"降到"不亏本"）；
--   - 若某个部署想恢复红线，把 sys_config.min_gross_margin 改回 0.15 即可，代码不用动。
UPDATE sys_config SET config_value = '0' WHERE config_key = 'min_gross_margin';
